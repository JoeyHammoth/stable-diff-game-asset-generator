"""Palette authoring: write a project palette from an authored image (docs/06, T21).

`sdga.config.read_palette` reads a palette; this module is its writing twin, and the only
place a palette file is produced. Extraction is deliberately a one-time, human-reviewed
step: `palette_snap` enforces whatever palette the project already has, so extracting a
palette per image would undo the colour lock the pipeline exists to provide.
"""

from __future__ import annotations

import math
from collections.abc import Sequence
from pathlib import Path

from .errors import ConfigError
from .postprocess.palette import RGB, extract_colours

_GPL_COLUMNS = 8
_PNG_COLUMNS = 8  # 16 colours become the 8x2 swatch grid the example project ships


def extract_palette(source: Path, max_colours: int = 16) -> tuple[RGB, ...]:
    """Read `source` and return at most `max_colours` of its colours, most used first."""
    from PIL import Image, UnidentifiedImageError

    try:
        with Image.open(source) as image:
            return extract_colours(image, max_colours)
    except (OSError, UnidentifiedImageError) as exc:
        raise ConfigError(f"cannot read image {source.name}: {exc}") from None


def write_palette(
    target: Path,
    colours: Sequence[RGB],
    *,
    name: str | None = None,
    source: str | None = None,
) -> Path:
    """Write `colours` to `target` as a `.gpl` or `.png` palette.

    Both formats read back through `read_palette` unchanged, so a project can switch between
    them without the palette's meaning changing; only the file hash, and therefore the seeds
    derived from it, differ.
    """
    checked = _checked(colours)
    path = Path(target)
    origin = f" from {source}" if source else ""

    if path.suffix.lower() == ".gpl":
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            _render_gpl(checked, name or path.stem, origin), encoding="utf-8", newline="\n"
        )
    elif path.suffix.lower() == ".png":
        _write_png(path, checked, origin)
    else:
        raise ConfigError(
            f"unsupported palette format {path.suffix!r}",
            location=path.name,
            remedy="write a .gpl file, or a .png swatch image",
        )
    return path


def _checked(colours: Sequence[RGB]) -> tuple[RGB, ...]:
    items = tuple(colours)
    if not items:
        raise ConfigError(
            "refusing to write an empty palette", remedy="extract at least one colour"
        )
    if len(items) > 256:
        raise ConfigError(
            f"{len(items)} colours is more than a pixel-art palette holds",
            remedy="extract 256 colours or fewer",
        )
    for colour in items:
        if (
            len(colour) != 3
            or any(isinstance(channel, bool) or not isinstance(channel, int) for channel in colour)
            or any(not 0 <= channel <= 255 for channel in colour)
        ):
            raise ConfigError(
                f"invalid colour {colour!r}", remedy="colours are three integers in 0-255"
            )
    return items


def _render_gpl(colours: Sequence[RGB], name: str, origin: str) -> str:
    header = [
        "GIMP Palette",
        f"Name: {name}",
        f"Columns: {_GPL_COLUMNS}",
        f"# Generated by `sdga palette extract`{origin}.",
        "# A one-time authoring aid: review it, commit it, then regenerate plan.json.",
    ]
    rows = [f"{r:3d} {g:3d} {b:3d}\t#{r:02x}{g:02x}{b:02x}" for r, g, b in colours]
    return "\n".join([*header, *rows]) + "\n"


def _write_png(target: Path, colours: Sequence[RGB], origin: str) -> None:
    from PIL import Image
    from PIL.PngImagePlugin import PngInfo

    columns = min(_PNG_COLUMNS, len(colours))
    rows = math.ceil(len(colours) / columns)
    image = Image.new("RGB", (columns, rows))
    for index, colour in enumerate(colours):
        image.putpixel((index % columns, index // columns), colour)

    # A PNG has nowhere to put a header comment, so the provenance rides in a text chunk;
    # without it the file would be an untraceable list of numbers.
    info = PngInfo()
    info.add_text(
        "Comment",
        f"Generated by `sdga palette extract`{origin}. One opaque pixel per colour, in scan order.",
    )
    target.parent.mkdir(parents=True, exist_ok=True)
    image.save(target, format="PNG", optimize=True, pnginfo=info)


__all__ = ["extract_palette", "write_palette"]
